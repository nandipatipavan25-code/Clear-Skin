            <h2 style="font-size: 1.75rem; font-weight: 800; color: var(--primary-dark); margin: 2rem 0 1rem 0;">What Is Skin Pigmentation?</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.8;">
                Skin pigmentation refers to the natural color of the skin, which is determined by melanin—a pigment produced by specialized cells called melanocytes. Melanin plays an essential role in protecting the skin from UV damage. However, when melanin production becomes excessive or uneven, it results in dark spots, patches, or uneven skin tone, commonly referred to as pigmentation. Conditions such as melasma, sun spots, tanning, and post-acne marks fall under this category.
            </p>

            <h2 style="font-size: 1.75rem; font-weight: 800; color: var(--primary-dark); margin: 2.25rem 0 1rem 0;">Common Causes of Pigmentation</h2>

            <ul style="margin-left: 1.25rem; margin-bottom: 2rem; display: flex; flex-direction: column; gap: 1.15rem; line-height: 1.8;">
                <li><strong>Sun Exposure:</strong> Prolonged exposure to ultraviolet (UV) rays is one of the primary causes of pigmentation. UV radiation stimulates melanocytes to produce more melanin as a defense mechanism, leading to tanning, sun spots, and patchy discoloration. Without proper sun protection, pigmentation tends to deepen over time, making pigmentation treatment more challenging.</li>
                <li><strong>Hormonal Changes:</strong> Hormonal fluctuations during pregnancy, menopause, or due to hormonal medications can trigger melasma. This type of pigmentation often appears as symmetrical brown or grayish patches on the face, especially on the cheeks, forehead, and upper lip.</li>
                <li><strong>Post-Inflammatory Hyperpigmentation (PIH):</strong> Dark marks that appear after acne, pimples, burns, or skin injuries are known as PIH. These marks develop as part of the skin’s healing process and are one of the most common reasons people seek treatment for dark spots.</li>
                <li><strong>Genetics and Skin Type:</strong> Some individuals are genetically predisposed to pigmentation, especially those with darker skin tones. Genetic factors influence how the skin reacts to sun exposure, inflammation, and aging.</li>
                <li><strong>Aging and Environmental Damage:</strong> Over time, cumulative sun exposure and environmental stressors can cause age spots, particularly on areas frequently exposed to sunlight, such as the face, hands, and neck.</li>
            </ul>

            <h2 style="font-size: 1.75rem; font-weight: 800; color: var(--primary-dark); margin: 2.25rem 0 1rem 0;">Why Home Remedies Often Fall Short</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.8;">
                Home remedies and over-the-counter creams may provide temporary lightening, but they rarely address the underlying cause of pigmentation. In some cases, improper use of products can worsen discoloration or irritate the skin. Since pigmentation often exists in deeper layers of the skin, professional dermatological intervention is essential for safe, long-lasting results.
            </p>

            <h2 style="font-size: 1.75rem; font-weight: 800; color: var(--primary-dark); margin: 2.25rem 0 1rem 0;">How Dermatology Can Effectively Treat Pigmentation</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.8;">
                Dermatology focuses on accurate diagnosis and personalized treatment based on skin type, pigmentation depth, and underlying causes.
            </p>

